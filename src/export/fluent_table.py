from __future__ import annotations

import argparse
import csv
import json
import pickle
from pathlib import Path

import numpy as np


def build_table(model, settings):
    log_gamma = np.linspace(
        np.log10(settings["shear_rate_min_s-1"]),
        np.log10(settings["shear_rate_max_s-1"]), settings["n_shear"],
    )
    phi = np.linspace(settings["phi_cb_min"], settings["phi_cb_max"], settings["n_phi"])
    log_eta = np.empty((len(phi), len(log_gamma)))
    for index, value in enumerate(phi):
        eta = model.predict(value, 10.0**log_gamma, False)["eta"]
        eta = np.clip(eta, settings["viscosity_min_Pa_s"], settings["viscosity_max_Pa_s"])
        log_eta[index] = np.log10(eta)
    return phi, log_gamma, log_eta


def interpolate_table(phi_value, gamma_value, phi_grid, log_gamma_grid, log_eta):
    p = np.clip(phi_value, phi_grid[0], phi_grid[-1])
    g = np.clip(np.log10(max(gamma_value, 1e-30)), log_gamma_grid[0], log_gamma_grid[-1])
    ip = min(np.searchsorted(phi_grid, p, side="right") - 1, len(phi_grid) - 2)
    ig = min(np.searchsorted(log_gamma_grid, g, side="right") - 1, len(log_gamma_grid) - 2)
    ip, ig = max(ip, 0), max(ig, 0)
    wp = (p - phi_grid[ip]) / (phi_grid[ip + 1] - phi_grid[ip])
    wg = (g - log_gamma_grid[ig]) / (log_gamma_grid[ig + 1] - log_gamma_grid[ig])
    value = ((1-wp)*(1-wg)*log_eta[ip, ig] + wp*(1-wg)*log_eta[ip+1, ig]
             + (1-wp)*wg*log_eta[ip, ig+1] + wp*wg*log_eta[ip+1, ig+1])
    return 10.0**value


def _c_array(name, values):
    body = ",\n    ".join("{:.12e}".format(float(x)) for x in np.ravel(values))
    return "static const real {}[] = {{\n    {}\n}};\n".format(name, body)


def write_header(path, phi, log_gamma, log_eta, settings):
    text = """/* Auto-generated by src.export.fluent_table; do not edit manually. */
#ifndef MODEL_C_TABLE_H
#define MODEL_C_TABLE_H
#define MODEL_C_N_PHI %d
#define MODEL_C_N_GAMMA %d
#define MODEL_C_ETA_MIN %.12e
#define MODEL_C_ETA_MAX %.12e
""" % (len(phi), len(log_gamma), settings["viscosity_min_Pa_s"], settings["viscosity_max_Pa_s"])
    text += _c_array("MODEL_C_PHI", phi)
    text += _c_array("MODEL_C_LOG_GAMMA", log_gamma)
    text += _c_array("MODEL_C_LOG_ETA", log_eta)
    text += "#endif\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="ascii")


def export(model_path, config_path, output_dir, udf_header):
    with model_path.open("rb") as stream:
        model = pickle.load(stream)
    config = json.loads(config_path.read_text(encoding="utf-8"))
    settings = config["fluent_table"]
    phi, log_gamma, log_eta = build_table(model, settings)
    output_dir.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(output_dir / "model_c_table.npz", phi=phi, log_gamma=log_gamma, log_eta=log_eta)
    with (output_dir / "model_c_table.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream); writer.writerow(["phi_cb", "shear_rate_s-1", "viscosity_Pa_s"])
        for ip, p in enumerate(phi):
            for ig, g in enumerate(log_gamma):
                writer.writerow([p, 10.0**g, 10.0**log_eta[ip, ig]])
    write_header(udf_header, phi, log_gamma, log_eta, settings)
    return phi, log_gamma, log_eta


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", type=Path, default=Path("artifacts/model_c/model_c.pkl"))
    parser.add_argument("--config", type=Path, default=Path("configs/model_c.json"))
    parser.add_argument("--output", type=Path, default=Path("artifacts/fluent_table"))
    parser.add_argument("--udf-header", type=Path, default=Path("udf/generated/model_c_table.h"))
    args = parser.parse_args()
    export(args.model, args.config, args.output, args.udf_header)


if __name__ == "__main__":
    main()
